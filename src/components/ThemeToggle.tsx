const ThemeToggle = () => {
  const { theme, toggleTheme } = useTheme();
  const isDark = theme === "dark";

  return (
    <button
      type="button"
      onClick={toggleTheme}
      aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
      className="flex size-8 sm:size-9 items-center justify-center rounded-full border border-s3 bg-s2/80 text-p4 backdrop-blur-md transition-colors hover:border-s4 active:scale-95"
    >
      {isDark ? <SunIcon /> : <MoonIcon />}
    </button>
  );
};

export default ThemeToggle;
